import { LEGAL } from "./config.js";

const esc = (s) => String(s ?? "").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

function operatorLine() {
  const parts = [LEGAL.name || "Продавец магазина «Синица»"];
  if (LEGAL.inn) parts.push(`ИНН ${LEGAL.inn}`);
  return parts.map(esc).join(", ");
}
function contacts() {
  const c = [`Telegram-бот <a href="https://t.me/sinitsa_chai_bot">@sinitsa_chai_bot</a>`];
  if (LEGAL.email) c.push(`электронная почта ${esc(LEGAL.email)}`);
  return c.join(", ");
}

